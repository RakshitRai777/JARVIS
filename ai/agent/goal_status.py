from enum import Enum, auto


class GoalStatus(Enum):
    """
    Represents the lifecycle of an agent goal.
    """

    ############################################################

    PENDING = auto()

    ############################################################

    ACTIVE = auto()

    ############################################################

    PAUSED = auto()

    ############################################################

    COMPLETED = auto()

    ############################################################

    FAILED = auto()

    ############################################################

    CANCELLED = auto()