from enum import Enum, auto


class ExecutionState(Enum):
    """
    Represents the lifecycle state
    of workflow execution.
    """

    ############################################################

    IDLE = auto()

    ############################################################

    RUNNING = auto()

    ############################################################

    PAUSED = auto()

    ############################################################

    COMPLETED = auto()

    ############################################################

    FAILED = auto()

    ############################################################

    CANCELLED = auto()