from enum import Enum


class RuntimeState(str, Enum):
    """
    Represents the current state of the Agent Runtime.
    """

    ############################################################

    IDLE = "idle"

    ############################################################

    RUNNING = "running"

    ############################################################

    WAITING = "waiting"

    ############################################################

    PAUSED = "paused"

    ############################################################

    COMPLETED = "completed"

    ############################################################

    FAILED = "failed"

    ############################################################

    CANCELLED = "cancelled"